export function getSpotlightProjects() {
  return portfolioProjects.filter((p) => p.featuredTier === "spotlight");
}

export function getGridProjects() {
  return portfolioProjects.filter((p) => p.featuredTier === "grid");
}

/** Portfolio page grid: spotlight + grid (excludes homepage flagships). */
export function getPortfolioGridProjects() {
  return portfolioProjects
    .filter((p) => p.featuredTier === "grid" || p.featuredTier === "spotlight")
    .map(enrichPortfolioProject);
}

function enrichPortfolioProject(project) {
  return applyPortfolioProjectMedia(project);
}

/** Ordered list for /portfolio work grid (flagship → spotlight → grid). */
export function getPortfolioPageProjects() {
  const tierOrder = { flagship: 0, spotlight: 1, grid: 2 };
  return [...portfolioProjects]
    .map(enrichPortfolioProject)
    .sort(
      (a, b) =>
        (tierOrder[a.featuredTier] ?? 9) - (tierOrder[b.featuredTier] ?? 9) ||
        (a.deckOrder ?? 99) - (b.deckOrder ?? 99)
    );
}

export function projectMatchesIndustryFilter(project, filterId) {
  if (filterId === "all") return true;
  return project.filterTags?.includes(filterId);
}

export function projectMatchesServiceFilter(project, filterId) {
  if (filterId === "all") return true;
  const row = portfolioServiceFilters.find((f) => f.id === filterId);
  if (!row?.matchTags) return true;
  const tags = [...(project.filterTags ?? []), ...(project.tags ?? []).map((t) => t.toLowerCase())];
  return row.matchTags.some((t) => tags.some((tag) => tag.includes(t)));
}

export function getProjectCardLabel(project) {
  if (project.category) return project.category;
  if (project.spotlightLabel) {
    return project.spotlightLabel.split("·")[0].trim();
  }
  return project.tags?.[0] ?? "Project";
}

export function getProjectHostname(url) {
  if (!url) return "";
  try {
    return new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return "";
  }
}

export function getHomeGridProjects() {
  return getPortfolioGridProjects();
}

export function getDeckProjectsByChapter(chapterId) {
  return portfolioProjects
    .filter((p) => p.deckChapter === chapterId)
    .sort((a, b) => (a.deckOrder ?? 99) - (b.deckOrder ?? 99));
}

export function getMosaicProjects() {
  return [...portfolioProjects].sort((a, b) => {
    const order = { large: 0, wide: 1, tall: 2, medium: 3, small: 4 };
    return (order[a.mosaicSize] ?? 5) - (order[b.mosaicSize] ?? 5);
  });
}
